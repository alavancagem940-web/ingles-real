export function explainCorrect(seed: PlacementSeed): string {
  return `${seed.english} quer dizer “${seed.meaning}”. ${seed.note}`
}

export function explainWrong(seed: PlacementSeed): string {
  return `A fala certa é ${seed.english}. O sentido é “${seed.meaning}”. ${seed.note}`
}

export function placementAudioLines(): Array<{ spoken: string; kind: 'native' | 'explain' }> {
  const lines: Array<{ spoken: string; kind: 'native' | 'explain' }> = []
  for (const seed of PLACEMENT_BANK) {
    lines.push({ spoken: seed.english, kind: 'native' })
    for (const phrase of seed.wrongEnglish) lines.push({ spoken: phrase, kind: 'native' })
    lines.push({ spoken: seed.meaning, kind: 'explain' })
    for (const phrase of seed.wrongMeanings) lines.push({ spoken: phrase, kind: 'explain' })
    lines.push({ spoken: explainCorrect(seed), kind: 'explain' })
    lines.push({ spoken: explainWrong(seed), kind: 'explain' })
  }
  return lines
}
